# PostgreSQL18 deparser output for exactly the trusted CHECK grammar above.
# Never evaluate a discovered expression to decide whether it is compatible.
_CHECK_DDL = {
    "status IN ('active','suspended')": "CHECK ((status = ANY (ARRAY['active'::text, 'suspended'::text])))",
    'revision>0': 'CHECK ((revision > 0))',
    'bytes>0 AND bytes<=8388608': 'CHECK (((bytes > 0) AND (bytes <= 8388608)))',
    'octet_length(content)=bytes': 'CHECK ((octet_length(content) = bytes))',
    "name IN ('code_key','native_key')": "CHECK ((name = ANY (ARRAY['code_key'::text, 'native_key'::text])))",
    'id=1': 'CHECK ((id = 1))',
}


def _ddl_items(definition):
    """Split only the fixed internal DDL, respecting groups and SQL literals."""
    items, start, depth, quoted, index = [], 0, 0, False, 0
    while index < len(definition):
        char = definition[index]
        if char == "'":
            if quoted and index + 1 < len(definition) and definition[index + 1] == "'":
                index += 2
                continue
            quoted = not quoted
        elif not quoted:
            if char == '(':
                depth += 1
            elif char == ')':
                depth -= 1
            elif char == ',' and depth == 0:
                items.append(definition[start:index].strip())
                start = index + 1
            if depth < 0:
                raise ValueError('Unsupported internal auxiliary DDL contract')
        index += 1
    if quoted or depth:
        raise ValueError('Unsupported internal auxiliary DDL contract')
    return (*items, definition[start:].strip())


def _ddl_contract():
    """Derive columns and keys from emitted DDL; reject unconsumed grammar."""
    result = {}
    kinds = {'TEXT': 'text', 'DOUBLE PRECISION': 'float8', 'INTEGER': 'int4',
             'BIGINT': 'int8', 'BYTEA': 'bytea'}
    for table, definition in ALL_TABLES.items():
        columns, constraints = [], []
        for item in _ddl_items(definition):
            unique = re.fullmatch(r'UNIQUE\(([a-z_,]+)\)', item)
            if unique:
                constraints.append(('u', tuple(unique[1].split(',')), None))
                continue
            match = re.fullmatch(r'([a-z_]+) (TEXT|DOUBLE PRECISION|INTEGER|BIGINT|BYTEA)(.*)', item)
            if not match:
                raise ValueError('Unsupported internal auxiliary DDL contract')
            name, kind, remaining = match.groups()
            not_null, identity, default = False, '', None
            while remaining.strip():
                remaining = remaining.strip()
                if remaining.startswith('GENERATED BY DEFAULT AS IDENTITY'):
                    identity, not_null = 'd', True
                    remaining = remaining[len('GENERATED BY DEFAULT AS IDENTITY'):]
                elif remaining.startswith('PRIMARY KEY'):
                    constraints.append(('p', (name,), None))
                    not_null, remaining = True, remaining[len('PRIMARY KEY'):]
                elif remaining.startswith('UNIQUE'):
                    constraints.append(('u', (name,), None))
                    remaining = remaining[len('UNIQUE'):]
                elif remaining.startswith('NOT NULL'):
                    not_null, remaining = True, remaining[len('NOT NULL'):]
                elif remaining.startswith('DEFAULT '):
                    match_default = re.fullmatch(r"DEFAULT (0|'\{\}')", remaining)
                    if not match_default:
                        raise ValueError('Unsupported internal auxiliary DDL default')
                    default = '0' if match_default[1] == '0' else "'{}'::text"
                    remaining = ''
                elif remaining.startswith('CHECK(') and remaining.endswith(')'):
                    expression = remaining[6:-1]
                    if expression not in _CHECK_DDL:
                        raise ValueError('Unsupported internal auxiliary CHECK contract')
                    constraints.append(('c', (), _CHECK_DDL[expression]))
                    remaining = ''
                else:
                    raise ValueError('Unsupported internal auxiliary DDL contract')
            columns.append((name, kinds[kind], not_null, identity, default))
            if not_null:
                constraints.append(('n', (name,), None))
        result[table] = (columns, Counter(constraints))
    return result


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), allow_nan=False)


def _digest(value):
    return hashlib.sha256(_canonical(value).encode()).hexdigest()


def _no_links(path):
    path = Path(path).absolute()
    if any(part.is_symlink() for part in (path, *path.parents)):
        raise ValueError('Linked preservation or cache paths are not supported')
    return path


def _read_file(path, maximum=None):
    path = _no_links(path)
    if not path.is_file() or (maximum is not None and path.stat().st_size > maximum):
        raise ValueError('Required preservation file is unavailable or exceeds its bound')
    return path.read_bytes()


def _audit(statuses, events):
    current = {row[0]: row[1:] for row in statuses}
    if len(current) != len(statuses):
        raise ValueError('Duplicate business status requires recovery')
    histories = {}
    for row in events:
        histories.setdefault(row[1], []).append(row)
    if set(current) != set(histories):
        raise ValueError('Business status and suspension audit require recovery together')
    for actor, rows in histories.items():
        rows.sort(key=lambda row: row[4])
        for revision, row in enumerate(rows, 1):
            if (row[2] not in ('active', 'suspended') or type(row[3]) is not int
                    or type(row[4]) is not int or (row[3], row[4]) != (revision - 1, revision)):
                raise ValueError('Incomplete business suspension audit requires recovery')
        latest = rows[-1]
        if tuple(current[actor]) != (latest[2], latest[4]):
            raise ValueError('Business status differs from its latest audit; restore together')


def _jpeg(data):
    from PIL import Image
    if not isinstance(data, bytes) or not data or len(data) > PHOTO_MAX_BYTES:
        raise ValueError('JPEG bytes exceed the bounded photo limit')
    try:
        with Image.open(io.BytesIO(data)) as image:
            if image.format != 'JPEG' or min(image.size) < 16 or image.width * image.height > 12000000:
                raise ValueError('Expected a bounded regular JPEG')
            image.load()
    except (OSError, Image.DecompressionBombError, Image.DecompressionBombWarning):
        raise ValueError('JPEG content is invalid') from None


def _photo(row):
    filename, actor, digest, length, created, content = row
    content = bytes(content)
    if (not isinstance(filename, str) or not PHOTO_NAME.fullmatch(filename)
            or not isinstance(actor, str) or not ACTOR_NAME.fullmatch(actor)
            or type(length) is not int or length != len(content)
            or not isinstance(created, (int, float)) or not math.isfinite(created)
            or digest != hashlib.sha256(content).hexdigest()):
        raise ValueError('Photo ownership, metadata and bytes require recovery together')
    _jpeg(content)
    return (filename, actor, digest, length, created, content)


class _Row:
    """The sqlite3.Row subset consumed by unchanged CodeStore methods."""
    def __init__(self, columns, values):
        self.columns, self.values = columns, values

    def keys(self):
        return self.columns

    def __getitem__(self, key):
        return self.values[self.columns.index(key)] if isinstance(key, str) else self.values[key]

    def __iter__(self):
        return iter(self.values)

    def __len__(self):
        return len(self.values)


class _Result:
    def __init__(self, cursor):
        self.cursor = cursor
        self.rowcount = cursor.rowcount
        self.columns = tuple(column.name for column in cursor.description or ())

    def fetchone(self):
        row = self.cursor.fetchone()
        return None if row is None else _Row(self.columns, row)

    def fetchall(self):
        return [_Row(self.columns, row) for row in self.cursor.fetchall()]

    def __iter__(self):
        for row in self.cursor:
            yield _Row(self.columns, row)


class _CodeSQL:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, statement, parameters=()):
        # These two introspections read actual established schema/version state.
        if statement == 'PRAGMA user_version':
            return _Result(self.connection.execute('SELECT legacy_version FROM auxiliary_state WHERE id=1'))
        if statement == "SELECT name FROM sqlite_master WHERE type='table' AND name IN ('business_status','business_status_events')":
            return _Result(self.connection.execute("SELECT tablename AS name FROM pg_catalog.pg_tables WHERE schemaname=pg_catalog.current_schema() AND tablename IN ('business_status','business_status_events')"))
        if (not isinstance(statement, str) or ';' in statement
                or not re.match(r'^(SELECT|INSERT|UPDATE|DELETE)\b', statement)):
            raise ValueError('SQL is outside the bounded CodeStore proof surface')
        referenced = re.findall(r'\b(?:FROM|JOIN|INTO)\s+([a-z_][a-z0-9_.]*)', statement, re.I)
        if statement.startswith('UPDATE '):
            referenced.append(statement.split()[1])
        if any(name not in TABLES for name in referenced):
            raise ValueError('SQL is outside the auxiliary application tables')
        ignore = statement.startswith('INSERT OR IGNORE INTO ')
        if ignore:
            statement = statement.replace('INSERT OR IGNORE INTO ', 'INSERT INTO ', 1) + ' ON CONFLICT DO NOTHING'
        # CodeStore statements have no quoted question marks or percent literals.
        if re.search(r"'[^']*\?[^']*'", statement) or '%' in statement:
            raise ValueError('Unsupported literal in CodeStore SQL')
        if statement.endswith(' ORDER BY d.updated'):
            statement += ' NULLS FIRST'  # SQLite's ascending NULL placement.
        return _Result(self.connection.execute(statement.replace('?', '%s'), parameters))


class PostgresAuxiliary:
    def __init__(self, dsn, schema):
        if any(name in os.environ for name in ('PGHOSTADDR', 'PGSERVICE', 'PGSERVICEFILE')):
            raise ValueError('Unset inherited libpq redirection for this disposable proof')
        try:
            settings = conninfo_to_dict(dsn)
        except Exception:
            raise ValueError('Invalid explicit disposable database configuration') from None
        if (settings.get('host') not in {'127.0.0.1', '::1', 'localhost'}
                or settings.get('hostaddr', '127.0.0.1') not in {'127.0.0.1', '::1'}
                or not settings.get('dbname', '').startswith('mlocal_aux_test_')
                or 'service' in settings or not isinstance(schema, str)
                or not re.fullmatch(r'mlocal_aux_test_[a-z0-9_]{1,47}', schema) or len(schema) > 63):
            raise ValueError('Only an explicitly owned loopback proof database/schema is supported')
        self.dsn, self.schema = dsn, schema

    @contextmanager
    def _connection(self):
        with psycopg.connect(self.dsn, connect_timeout=5) as connection:
            connection.execute('SET LOCAL search_path TO pg_catalog')
            if not connection.execute('SELECT pg_catalog.current_database()').fetchone()[0].startswith('mlocal_aux_test_'):
                raise ValueError('Refusing a non-fixture database')
            exists = connection.execute('SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname=%s', (self.schema,)).fetchone()
            if not exists:
                raise ValueError('The explicitly owned schema must already exist')
            connection.execute("SET LOCAL lock_timeout='15s'")
            connection.execute("SET LOCAL statement_timeout='30s'")
            connection.execute("SET LOCAL idle_in_transaction_session_timeout='30s'")
            yield connection

    def _names(self, connection):
        return {row[0] for row in connection.execute('SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname=%s', (self.schema,))}

    def _catalog(self, connection):
        """Read-only admission of this adapter's emitted PostgreSQL18 schema.

        Requires quiescent schema ownership; this is not a privileged DDL fence.
        Names/OIDs and the identity counter are not declaration semantics.
        """
        # Schema-local operators must not run while inspecting an untrusted schema.
        connection.execute('SET LOCAL search_path TO pg_catalog')
        if connection.info.server_version // 10000 != 18:
            raise ValueError('Auxiliary catalog admission requires qualified PostgreSQL18')
        expected = _ddl_contract()

        def require(condition):
            if not condition:
                raise ValueError('Incompatible auxiliary DDL requires explicit recovery or migration')

        classes = connection.execute("SELECT 'pg_catalog.pg_class'::pg_catalog.regclass::oid, 'pg_catalog.pg_type'::pg_catalog.regclass::oid, 'pg_catalog.pg_constraint'::pg_catalog.regclass::oid").fetchone()
        relations = connection.execute("""
            SELECT c.oid,c.relname,c.relkind,c.relpersistence,c.relispartition,
                   c.relrowsecurity,c.relforcerowsecurity,c.relchecks,c.reltype,c.reloftype,am.amname
            FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
            LEFT JOIN pg_catalog.pg_am am ON am.oid=c.relam
            WHERE n.nspname=%s
        """, (self.schema,)).fetchall()
        tables = {row[1]: row[0] for row in relations if row[2] == 'r'}
        require(set(tables) == set(expected))
        require(all(row[2] in ('r', 'i', 'S') and row[3] == 'p'
                    and not any(row[4:7]) and row[9] == 0
                    and (row[2] != 'r' or row[10] == 'heap') for row in relations))
        table_ids = list(tables.values())
        require(not connection.execute("""
            SELECT 1 FROM pg_catalog.pg_inherits
            WHERE inhrelid=ANY(%s) OR inhparent=ANY(%s)
        """, (table_ids, table_ids)).fetchone())
        require(not connection.execute("""
            SELECT 1 FROM pg_catalog.pg_trigger WHERE tgrelid=ANY(%s)
            UNION ALL SELECT 1 FROM pg_catalog.pg_rewrite WHERE ev_class=ANY(%s)
            UNION ALL SELECT 1 FROM pg_catalog.pg_policy WHERE polrelid=ANY(%s)
        """, (table_ids, table_ids, table_ids)).fetchone())

        attributes = connection.execute("""
            SELECT a.attrelid,a.attnum,a.attname,t.typname,n.nspname,a.atttypmod,
                   a.attndims,a.attnotnull,a.attidentity,a.attgenerated,a.attisdropped,
                   a.attislocal,a.attinhcount,a.atthasmissing,a.attcollation=t.typcollation,
                   pg_catalog.pg_get_expr(d.adbin,d.adrelid)
            FROM pg_catalog.pg_attribute a
            LEFT JOIN pg_catalog.pg_type t ON t.oid=a.atttypid
            LEFT JOIN pg_catalog.pg_namespace n ON n.oid=t.typnamespace
            LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
            WHERE a.attrelid=ANY(%s) AND a.attnum>0 ORDER BY a.attrelid,a.attnum
        """, (table_ids,)).fetchall()
        by_table, column_names = {}, {}
        for row in attributes:
            relation, number, name, kind, namespace, typmod, dimensions, not_null, identity, generated, dropped, local, inherited, missing, collation, default = row
            require(namespace == 'pg_catalog' and typmod == -1 and dimensions == 0
                    and not generated and not dropped and local and inherited == 0
                    and not missing and collation)
            by_table.setdefault(relation, []).append((name, kind, not_null, identity, default))
            column_names[(relation, number)] = name
        for table, (columns, _) in expected.items():
            require(by_table.get(tables[table]) == columns)

        constraints = connection.execute("""
            SELECT c.oid,c.conrelid,c.contype,c.conkey,c.conindid,c.condeferrable,
                   c.condeferred,c.convalidated,c.conenforced,c.conislocal,c.coninhcount,
                   c.conparentid,c.connoinherit,pg_catalog.pg_get_constraintdef(c.oid)
            FROM pg_catalog.pg_constraint c JOIN pg_catalog.pg_namespace n ON n.oid=c.connamespace
            WHERE n.nspname=%s
        """, (self.schema,)).fetchall()
        actual_constraints, key_indexes = {}, {}
        for row in constraints:
            oid, relation, kind, keys, index, deferrable, deferred, valid, enforced, local, inherited, parent, noinherit, declaration = row
            require(relation in table_ids and kind in ('p', 'u', 'c', 'n')
                    and not deferrable and not deferred and valid and enforced
                    and local and inherited == 0 and parent == 0)
            require(noinherit == (kind in ('p', 'u')))
            require(kind in ('p', 'u') or index == 0)
            key = () if kind == 'c' else tuple(column_names.get((relation, number)) for number in keys or ())
            actual_constraints.setdefault(relation, []).append((kind, key, declaration if kind == 'c' else None))
            if kind in ('p', 'u'):
                require(index not in key_indexes and index != 0)
                key_indexes[index] = (relation, kind, key)
        for table, (_, wanted) in expected.items():
            require(Counter(actual_constraints.get(tables[table], [])) == wanted)
            relation = next(row for row in relations if row[0] == tables[table])
            require(relation[7] == sum(count for (kind, _, _), count in wanted.items() if kind == 'c'))

        indexes = connection.execute("""
            SELECT i.indexrelid,i.indrelid,i.indisunique,i.indisprimary,i.indisexclusion,
                   i.indimmediate,i.indisvalid,i.indisready,i.indislive,i.indnullsnotdistinct,
                   i.indnkeyatts,i.indnatts,i.indkey::int2[],i.indclass::oid[],
                   i.indcollation::oid[],i.indoption::int2[],i.indexprs IS NULL,
                   i.indpred IS NULL,am.amname
            FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class c ON c.oid=i.indexrelid
            JOIN pg_catalog.pg_am am ON am.oid=c.relam WHERE i.indrelid=ANY(%s)
        """, (table_ids,)).fetchall()
        opclasses = {row[0]: row[1:] for row in connection.execute("""
            SELECT o.oid,n.nspname,o.opcdefault,t.typname,am.amname,o.opckeytype FROM pg_catalog.pg_opclass o
            JOIN pg_catalog.pg_namespace n ON n.oid=o.opcnamespace
            JOIN pg_catalog.pg_type t ON t.oid=o.opcintype
            JOIN pg_catalog.pg_am am ON am.oid=o.opcmethod
        """).fetchall()}
        column_types = {(tables[table], number): kind for table, (columns, _) in expected.items()
                        for number, (_, kind, _, _, _) in enumerate(columns, 1)}
        collations = {(row[0], row[1]): row[2] for row in connection.execute("""
            SELECT attrelid,attnum,attcollation FROM pg_catalog.pg_attribute
            WHERE attrelid=ANY(%s) AND attnum>0
        """, (table_ids,)).fetchall()}
        index_ids, sends_indexes = set(), 0
        for row in indexes:
            oid, relation, unique, primary, exclusion, immediate, valid, ready, live, nulls_distinct, count, total, keys, classes_used, index_collations, options, plain, unfiltered, method = row
            require(not exclusion and immediate and valid and ready and live and not nulls_distinct
                    and count == total and count == len(keys) and all(number > 0 for number in keys)
                    and plain and unfiltered and method == 'btree')
            names = tuple(column_names.get((relation, number)) for number in keys)
            if oid in key_indexes:
                wanted_relation, kind, wanted_keys = key_indexes[oid]
                require(relation == wanted_relation and names == wanted_keys and unique
                        and primary == (kind == 'p'))
            else:
                require(relation == tables['sends'] and names == ('email', 'at')
                        and not unique and not primary)
                sends_indexes += 1
            require(len(classes_used) == count and len(index_collations) == count and len(options) == count)
            for number, opclass, collation, option in zip(keys, classes_used, index_collations, options):
                require(opclasses.get(opclass) == ('pg_catalog', True, column_types[(relation, number)], 'btree', 0)
                        and collation == collations[(relation, number)] and option == 0)
            index_ids.add(oid)
        require(sends_indexes == 1 and set(key_indexes) <= index_ids)
        require(index_ids == {row[0] for row in relations if row[2] == 'i'})

        sequences = connection.execute("""
            SELECT s.seqrelid,t.typname,n.nspname,s.seqstart,s.seqincrement,s.seqmax,
                   s.seqmin,s.seqcache,s.seqcycle
            FROM pg_catalog.pg_sequence s JOIN pg_catalog.pg_type t ON t.oid=s.seqtypid
            JOIN pg_catalog.pg_namespace n ON n.oid=t.typnamespace
            WHERE s.seqrelid=ANY(%s)
        """, ([row[0] for row in relations if row[2] == 'S'],)).fetchall()
        require(len(sequences) == 1)
        sequence, *declaration = sequences[0]
        require(declaration == ['int8', 'pg_catalog', 1, 1, 9223372036854775807, 1, 1, False])
        review_id = next(number for (relation, number), name in column_names.items()
                         if relation == tables['business_reviews'] and name == 'id')
        ownership = connection.execute("""
            SELECT refobjid,refobjsubid,deptype FROM pg_catalog.pg_depend
            WHERE classid='pg_catalog.pg_class'::pg_catalog.regclass AND objid=%s
              AND refclassid='pg_catalog.pg_class'::pg_catalog.regclass
        """, (sequence,)).fetchall()
        require(ownership == [(tables['business_reviews'], review_id, 'i')])

        # Exact namespace ownership rejects functions, domains and other hidden
        # execution objects, including schemas with no ordinary tables at all.
        types = connection.execute("""
            SELECT t.oid,t.typrelid,t.typelem,t.typtype,t.typarray
            FROM pg_catalog.pg_type t JOIN pg_catalog.pg_namespace n ON n.oid=t.typnamespace
            WHERE n.nspname=%s
        """, (self.schema,)).fetchall()
        row_types = {row[1]: row for row in types if row[3] == 'c' and row[1] in table_ids}
        require(set(row_types) == set(table_ids))
        require(all(row_types[row[0]][0] == row[8] for row in relations if row[2] == 'r'))
        allowed_types = set()
        for row in row_types.values():
            oid, relation, element, kind, array = row
            require(element == 0 and any(candidate[:4] == (array, 0, oid, 'b') for candidate in types))
            allowed_types.update((oid, array))
        require({row[0] for row in types} == allowed_types)
        type_dependencies = connection.execute("""
            SELECT objid,refclassid,refobjid,refobjsubid FROM pg_catalog.pg_depend
            WHERE classid='pg_catalog.pg_type'::pg_catalog.regclass AND objid=ANY(%s) AND deptype='i'
        """, (list(allowed_types),)).fetchall()
        wanted_dependencies = {(row[0], classes[0], row[1], 0) for row in row_types.values()}
        wanted_dependencies.update((row[4], classes[1], row[0], 0) for row in row_types.values())
        require(set(type_dependencies) == wanted_dependencies)
        allowed = {(classes[0], row[0], 0) for row in relations}
        allowed.update((classes[1], oid, 0) for oid in allowed_types)
        allowed.update((classes[2], row[0], 0) for row in constraints)
        require(set(self._namespace_objects(connection)) <= allowed)
        connection.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(self.schema)))

    def _namespace_objects(self, connection):
        return connection.execute("""
            SELECT d.classid,d.objid,d.objsubid FROM pg_catalog.pg_depend d
            JOIN pg_catalog.pg_namespace n ON n.oid=d.refobjid
            WHERE d.refclassid='pg_catalog.pg_namespace'::pg_catalog.regclass AND n.nspname=%s
        """, (self.schema,)).fetchall()

    def _validate(self, connection):
        self._catalog(connection)
        self._validate_values(connection)

    def _validate_values(self, connection):
        state = connection.execute('SELECT id,schema_version,legacy_version FROM auxiliary_state').fetchall()
        if state != [(1, VERSION, 1)]:
            raise ValueError('Incompatible auxiliary schema version; no automatic reset')
        _audit(connection.execute('SELECT * FROM business_status').fetchall(),
               connection.execute('SELECT * FROM business_status_events').fetchall())

    def initialize(self):
        with self._connection() as connection:
            if self._namespace_objects(connection):
                self._catalog(connection)
                connection.execute('SELECT id FROM auxiliary_state WHERE id=1 FOR UPDATE')
                self._validate_values(connection)
                return
            # Explicit disposable fixture creation only. Selection never calls it.
            connection.execute(sql.SQL('SET LOCAL search_path TO {}, pg_catalog').format(sql.Identifier(self.schema)))
            for name, definition in ALL_TABLES.items():
                connection.execute(sql.SQL('CREATE TABLE {} ({})').format(sql.Identifier(name), sql.SQL(definition)))
            connection.execute('CREATE INDEX sends_email_at ON sends(email,at)')
            self._catalog(connection)
            connection.execute('INSERT INTO auxiliary_state(id,schema_version,legacy_version) VALUES (1,%s,1)', (VERSION,))
            self._validate_values(connection)

    @contextmanager
    def _locked(self):
        with self._connection() as connection:
            self._catalog(connection)
            connection.execute('SELECT id FROM auxiliary_state WHERE id=1 FOR UPDATE')
            self._validate_values(connection)
            yield connection

    @contextmanager
    def transaction(self):
        with self._locked() as connection:
            yield _CodeSQL(connection)

    def _snapshot(self, connection):
        result = {}
        for table in (*TABLES, 'photos', 'signing_material'):
            rows = connection.execute(sql.SQL('SELECT * FROM {}').format(sql.Identifier(table))).fetchall()
            normalized = [[{'bytea': bytes(value).hex()} if isinstance(value, (bytes, memoryview)) else value for value in row] for row in rows]
            result[table] = sorted(normalized, key=_canonical)
        return result

    def _legacy_database(self, path, expected, version=None):
        path = _no_links(path)
        if any(Path(str(path) + suffix).exists() for suffix in ('-wal', '-shm', '-journal')):
            raise ValueError('Quiesce and preserve the SQLite store before import')
        raw = _read_file(path)
        database = sqlite3.connect(':memory:')
        try:
            database.deserialize(raw)
            database.execute('PRAGMA query_only=ON')
            if database.execute('PRAGMA integrity_check').fetchall() != [('ok',)]:
                raise ValueError('Legacy SQLite integrity check failed')
            names = {row[0] for row in database.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")}
            if names != set(expected):
                raise ValueError('Legacy SQLite tables are incomplete or unknown')
            if version is not None and database.execute('PRAGMA user_version').fetchone()[0] != version:
                raise ValueError('Legacy schema version requires explicit migration')
            rows = {}
            for table, columns in expected.items():
                actual = tuple(row[1] for row in database.execute('PRAGMA table_info(' + table + ')'))
                if actual != columns:
                    raise ValueError('Legacy SQLite columns require explicit migration')
                rows[table] = database.execute('SELECT * FROM ' + table).fetchall()
            return rows, hashlib.sha256(raw).hexdigest()
        finally:
            database.close()

    def import_legacy(self, onboarding_path, photo_registry_path, photos_dir, code_key_path, native_key_path):
        records, onboarding_hash = self._legacy_database(onboarding_path, COLUMNS, 1)
        registry, photo_hash = self._legacy_database(photo_registry_path, {'photos': PHOTO_COLUMNS[:-1]})
        _audit(records['business_status'], records['business_status_events'])
        code_key, native_key = _read_file(code_key_path, 32), _read_file(native_key_path, 65536)
        if len(code_key) != 32 or not native_key:
            raise ValueError('Original signing material is incomplete')
        directory = _no_links(photos_dir)
        if not directory.is_dir():
            raise ValueError('Original photos directory is required')
        files = {path.name for path in directory.iterdir()}
        if files != {row[0] for row in registry['photos']}:
            raise ValueError('Unknown or missing legacy photo files require reconciliation')
        photos = [_photo((*row, _read_file(directory / row[0], PHOTO_MAX_BYTES))) for row in registry['photos']]
        if sum(row[3] for row in photos) > PHOTO_TOTAL_MAX_BYTES:
            raise ValueError('Legacy photos exceed the bounded proof capacity')
        summary = {table: len(rows) for table, rows in records.items()}
        summary.update(photos=len(photos), photo_bytes=sum(row[3] for row in photos), signing_keys=2)
        digest = _digest({'onboarding': onboarding_hash, 'registry': photo_hash,
                          'keys': [hashlib.sha256(value).hexdigest() for value in (code_key, native_key)],
                          'photos': sorted((row[0], row[2]) for row in photos)})
        with self._locked() as connection:
            previous = connection.execute('SELECT import_digest,import_summary,imported_state_digest FROM auxiliary_state WHERE id=1').fetchone()
            if previous[0] is not None:
                if previous[0] != digest or previous[2] != _digest(self._snapshot(connection)):
                    raise ValueError('Import conflicts with preserved or subsequently changed state')
                return {'digest': previous[0], 'summary': json.loads(previous[1])}
            if any(self._snapshot(connection).values()):
                raise ValueError('Import requires an empty initialized target')
            for table, rows in records.items():
                query = sql.SQL('INSERT INTO {} VALUES ({})').format(sql.Identifier(table), sql.SQL(',').join(sql.Placeholder() for _ in COLUMNS[table]))
                for row in rows:
                    connection.execute(query, row)
            for name, material in (('code_key', code_key), ('native_key', native_key)):
                connection.execute('INSERT INTO signing_material VALUES (%s,%s)', (name, material))
            for row in photos:
                connection.execute('INSERT INTO photos VALUES (%s,%s,%s,%s,%s,%s)', row)
            maximum = connection.execute('SELECT MAX(id) FROM business_reviews').fetchone()[0]
            next_id = maximum + 1 if maximum is not None else 1
            connection.execute(sql.SQL('ALTER TABLE business_reviews ALTER COLUMN id RESTART WITH {}').format(sql.Literal(next_id)))
            self._validate(connection)
            connection.execute('UPDATE auxiliary_state SET import_digest=%s,import_summary=%s,imported_state_digest=%s WHERE id=1', (digest, _canonical(summary), _digest(self._snapshot(connection))))
        return {'digest': digest, 'summary': summary}

    def signing_material(self):
        with self._locked() as connection:
            keys = {name: bytes(material) for name, material in connection.execute('SELECT name,material FROM signing_material')}
            if set(keys) != {'code_key', 'native_key'} or len(keys['code_key']) != 32 or not keys['native_key']:
                raise ValueError('Preserved signing material is unavailable')
            return keys

    def code_store(self, store_class, directory, clock):
        # Avoid postinit: it creates SQLite/key files. Never patch the class.
        instance = store_class.__new__(store_class)
        instance.directory = Path(directory)
        instance.path = instance.directory / 'onboarding.sqlite3'
        instance.clock = clock
        instance.key = self.signing_material()['code_key']
        instance.transaction = self.transaction
        return instance

    def photo_save(self, actor, filename, jpeg_bytes, created):
        if (not isinstance(actor, str) or not ACTOR_NAME.fullmatch(actor)
                or not isinstance(filename, str) or not PHOTO_NAME.fullmatch(filename)
                or not isinstance(created, (int, float)) or not math.isfinite(created)):
            raise ValueError('Invalid trusted photo metadata')
        _jpeg(jpeg_bytes)
        digest = hashlib.sha256(jpeg_bytes).hexdigest()
        with self._locked() as connection:
            collision = connection.execute('SELECT * FROM photos WHERE filename=%s', (filename,)).fetchone()
            if collision is not None:
                collision = _photo(collision)
                if collision[1] != actor or collision[2] != digest or collision[5] != jpeg_bytes:
                    raise ValueError('Photo filename already belongs to different content or owner')
            same = connection.execute('SELECT * FROM photos WHERE actor=%s AND digest=%s', (actor, digest)).fetchone()
            if same is not None:
                same = _photo(same)
                if same[5] != jpeg_bytes:
                    raise ValueError('Existing photo bytes require recovery')
                return same[0]
            total, actor_total, recent = connection.execute('SELECT COALESCE(SUM(bytes),0),COALESCE(SUM(bytes) FILTER(WHERE actor=%s),0),COUNT(*) FILTER(WHERE actor=%s AND created>%s) FROM photos', (actor, actor, created - 86400)).fetchone()
            if (actor_total + len(jpeg_bytes) > PHOTO_ACTOR_MAX_BYTES or total + len(jpeg_bytes) > PHOTO_TOTAL_MAX_BYTES or recent >= PHOTO_DAILY_LIMIT):
                raise ValueError('Bounded photo storage quota reached')
            connection.execute('INSERT INTO photos VALUES (%s,%s,%s,%s,%s,%s)', (filename, actor, digest, len(jpeg_bytes), created, jpeg_bytes))
            return filename

    def photo_owned(self, filename, actor):
        if not isinstance(filename, str) or not PHOTO_NAME.fullmatch(filename):
            return False
        with self._locked() as connection:
            row = connection.execute('SELECT * FROM photos WHERE filename=%s AND actor=%s', (filename, actor)).fetchone()
            return row is not None and bool(_photo(row))

    def materialize_photos(self, cache_dir):
        directory = _no_links(cache_dir)
        if directory.exists() and (not directory.is_dir() or any(directory.iterdir())):
            raise ValueError('Photo materialization requires a fresh empty disposable cache')
        with self._locked() as connection:
            photos = [_photo(row) for row in connection.execute('SELECT * FROM photos ORDER BY filename')]
        directory.mkdir(parents=True, exist_ok=True)
        if any(directory.iterdir()):
            raise ValueError('Photo materialization requires a fresh empty disposable cache')
        for filename, actor, digest, length, created, content in photos:
            descriptor, temporary = tempfile.mkstemp(prefix='.photo-', dir=directory)
            try:
                with os.fdopen(descriptor, 'wb') as stream:
                    stream.write(content)
                    stream.flush()
                    os.fsync(stream.fileno())
                os.replace(temporary, directory / filename)
            finally:
                Path(temporary).unlink(missing_ok=True)
